/**
 * /shared/sync-constants.js
 * Run BEFORE each module session starts: `node ../shared/sync-constants.js`
 * Copies /shared/constants.js -> /frontend/src/constants/sharedConstants.js
 * converted to `export default {...}` syntax for Vite's ES module frontend.
 *
 * No module edits sharedConstants.js by hand (Master Spec Section 7).
 */
const fs = require('fs');
const path = require('path');

const SOURCE = path.join(__dirname, 'constants.js');
const DEST = path.join(__dirname, '..', 'frontend', 'src', 'constants', 'sharedConstants.js');

function main() {
  delete require.cache[require.resolve(SOURCE)];
  const constants = require(SOURCE);

  const banner =
    '// AUTO-GENERATED by /shared/sync-constants.js — DO NOT EDIT BY HAND.\n' +
    '// Source of truth: /shared/constants.js\n\n';

  const body = `export default ${JSON.stringify(constants, null, 2)};\n`;

  fs.mkdirSync(path.dirname(DEST), { recursive: true });
  fs.writeFileSync(DEST, banner + body, 'utf8');
  console.log(`[sync-constants] Wrote ${DEST}`);
}

main();
